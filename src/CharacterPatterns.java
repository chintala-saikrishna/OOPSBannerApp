public class CharacterPatterns {

    public void printO() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
    }

    public void printP() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*");
        System.out.println("*");
    }

    public void printS() {
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*");
        System.out.println("*****");
        System.out.println("    *");
        System.out.println("    *");
        System.out.println("*****");
    }
}