public class OOPSBannerApp {

    public static void main(String[] args) {
        printO();
        System.out.print("   ");
        printO();
        System.out.print("   ");
        printP();
        System.out.print("   ");
        printS();
    }

    public static void printO() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
    }

    public static void printP() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*");
        System.out.println("*");
    }

    public static void printS() {
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*");
        System.out.println("*****");
        System.out.println("    *");
        System.out.println("    *");
        System.out.println("*****");
    }
}